// Generate 30-day uptime bars
function generateDailyUptime(baseUptime: number, hasMinorDrop: boolean = false) {
  const days = [];
  const now = new Date();
  for (let i = 29; i >= 0; i--) {
    const d = new Date(now.getTime() - i * 24 * 60 * 60 * 1000);
    const dateStr = d.toISOString().split('T')[0];
    let uptime = baseUptime + (Math.random() * 0.05 - 0.02);
    let status: 'operational' | 'degraded' | 'outage' = 'operational';
    let incidents = 0;

    if (hasMinorDrop && i === 12) {
      uptime = 98.4;
      status = 'degraded';
      incidents = 1;
    }
    if (uptime > 100) uptime = 100;
    if (uptime < 98) uptime = 98.2;

    days.push({
      date: dateStr,
      uptime: parseFloat(uptime.toFixed(2)),
      status,
      incidents,
    });
  }
  return days;
}

