/**
 * Quick lookup Map for System Roles by code or name
 */
export const SYSTEM_ROLES_MAP = new Map<string, Role>(
  SYSTEM_ROLE_TEMPLATES.map((r) => [r.name.toLowerCase(), r])
);

export function getSystemRole(roleNameOrCode: string): Role | undefined {
  const normalized = roleNameOrCode.toLowerCase().trim();
  const stripped = normalized.replace(/[\s_-]+/g, '');
  return (
    SYSTEM_ROLE_TEMPLATES.find(
      (r) =>
        r.name.toLowerCase() === normalized ||
        r.code.toLowerCase() === normalized ||
        r.name.toLowerCase().replace(/[\s_-]+/g, '') === stripped ||
        r.code.toLowerCase().replace(/[\s_-]+/g, '') === stripped
    ) || undefined
  );
}
